def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="install.py", description="omnigate Stage 2/3 installer")
    p.add_argument("--method", choices=["vm", "kexec", "ghost", "full-wipe"], default="vm",
                   help="Install method (default: vm)")
    p.add_argument("--host", help="Target host (for ghost method)")
    p.add_argument("--iso", help="Path to omarchy ISO (kexec/vm)")
    p.add_argument("--attach", help="Directory to attach as 9p share (vm)")
    p.add_argument("--disk", help="Target disk (ghost)")
    p.add_argument("--size-gb", type=int, default=20, help="Arch partition/subvol size (ghost)")
    p.add_argument("--mem", type=int, default=4096, help="QEMU memory MB (vm)")
    p.add_argument("--smp", type=int, help="QEMU CPU cores (vm)")
    p.add_argument("--display", default="none", help="QEMU display backend (vm)")
    p.add_argument("--timeout", type=int, default=600, help="QEMU timeout (vm)")
    p.add_argument("--ip", help="Static IP for kexec")
    p.add_argument("--kmsg", help="Extra kernel cmdline for kexec")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--yes", action="store_true")
    opts = p.parse_args(argv)

    if opts.method == "vm":
        return method_vm(opts)
    elif opts.method == "kexec":
        return method_kexec(opts)
    elif opts.method == "ghost":
        return method_ghost(opts)
    elif opts.method == "full-wipe":
        print("full-wipe not yet implemented — use --method ghost")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())