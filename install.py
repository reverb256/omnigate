def build_ghost_script(host: str, plan: dict) -> str:
    """Generate subvolume-based ghost-drive install script.

    KEY FIX: Does NOT resize the btrfs partition. Instead, creates a new
    subvolume (e.g. /dev/nvme0n1p2 → /@arch-root) and installs Arch there.
    The old NixOS @ subvolume stays intact for instant rollback.
    """
    p = plan.get("partitions", {})
    disk = p.get("current_disk", "nvme0n1")
    btrfs_part = p.get("btrfs_partition", f"/dev/{disk}p2")
    arch_subvol_name = f"@{host}-arch"
    arch_mount = f"/mnt/{host}-arch"

    services = plan.get("services", [])
    mapped = [s for s in services if s.get("status") == "mapped"]
    deferred = [s for s in services if s.get("status") == "defer"]

    lines = [
        "#!/usr/bin/env bash",
        f"# Ghost-subvolume Arch + omarchy install for {host}",
        f"# Strategy: subvolume install (NO partition resize — instant rollback via bootloader)",
        "# Generated by install.py — COMMIT + REVIEW BEFORE EXECUTING",
        "set -euo pipefail",
        "",
        "# --- Pre-flight checks ---",
        f"echo 'Target: {host} on {disk}'",
        f"df -h {btrfs_part}",
        "btrfs filesystem usage / | grep -E 'Device size|Used|Free'",
        "",
        "# 1. Create new btrfs subvolume for Arch (old NixOS @ stays intact)",
        f"btrfs subvolume create /{arch_subvol_name}",
        f"echo 'Created subvolume /{arch_subvol_name}'",
        "",
        "# 2. Mount Arch subvolume for pacstrap",
        f"mkdir -p {arch_mount}",
        f"mount -o subvol=/{arch_subvol_name} {btrfs_part} {arch_mount}",
        "",
        "# 3. Install Arch base",
        "pacstrap " + arch_mount + " base linux linux-firmware --noconfirm",
        "",
        "# 4. Create fstab with both subvolumes (Arch default + NixOS ghost)",
        f"genfstab -U {arch_mount} > {arch_mount}/etc/fstab",
        "# Add ghost-mount entry for NixOS rollback",
        f"echo '# NixOS ghost partition (readonly rollback)' >> {arch_mount}/etc/fstab",
        f"echo '{btrfs_part} {arch_mount}/nixos-legacy btrfs subvol=/@,ro 0 2' >> {arch_mount}/etc/fstab",
        "",
        "# 5. Chroot into Arch, install omarchy",
        f"arch-chroot {arch_mount} /bin/bash -c 'pacman -Syu --noconfirm grub efibootmgr'",
        f"arch-chroot {arch_mount} /bin/bash -c 'grub-install --target=x86_64-efi --efi-directory=/boot --removable'",
        f"arch-chroot {arch_mount} /bin/bash -c 'grub-mkconfig -o /boot/‌grub/grub.cfg'",
        f"echo 'Install omarchy via: curl -fsSL https://get.omarchy.dev | bash'",
        "",
        "# 6. Port services (from NixOS ghost mount)",
        f"mkdir -p {arch_mount}/nixos-legacy",
        f"# In arch chroot:",
    ]

    for svc in mapped:
        name = svc.get("name", "")
        equiv = svc.get("arch_equivalent", "")
        units = svc.get("systemd_units", [])
        target = svc.get("target_path", "")
        lines.append(f"  # {name} → {equiv}")
        if units:
            lines.append(f"  systemctl enable {' '.join(units)}")
        if target:
            lines.append(f"  mkdir -p {target}")
            if svc.get("install"):
                lines.append(f"  {svc['install']}")

    if deferred:
        lines.append("  # Deferred to omarchy (handled by omarchy setup):")
        for svc in deferred:
            lines.append(f"  # {svc.get('name')} → {svc.get('arch_equivalent')}")

    lines += [
        "",
        "# 7. Port secrets (from critical-configs backup)",
        "mkdir -p " + arch_mount + "/etc/age",
        f"  cp -a /mnt/sentry-backup/critical-configs/nixos/.age/ {arch_mount}/etc/age/",
        "mkdir -p " + arch_mount + "/etc/omnigate",
        f"  cp -a /mnt/sentry-backup/critical-configs/nixos/secretspec.toml {arch_mount}/etc/omnigate/",
        "mkdir -p " + arch_mount + "/etc/ssh",
        f"  cp -a /mnt/sentry-backup/home-j_kro/.ssh/* {arch_mount}/etc/ssh/ 2>/dev/null || true",
        "",
        "# 8. Port user configs via symlinks (NOT copies)",
        "# User preference: symlinks to ghost-mounted preserved dirs",
        f"  mkdir -p {arch_mount}/home/j_kro/.config",
        f"  rmdir {arch_mount}/home/j_kro/.config 2>/dev/null || true",
        f"  ln -sd /nixos-legacy/home/j_kro/.config {arch_mount}/home/j_kro/.config",
        f"  ln -sd /nixos-legacy/home/j_kro/.ssh {arch_mount}/home/j_kro/.ssh",
        f"  ln -sd /nixos-legacy/home/j_kro/.hermes {arch_mount}/home/j_kro/.hermes",
        "",
        "# 9. Port pipeWire fix (rt kernel params — the fix we verified)",
        f"  mkdir -p {arch_mount}/etc/pipewire/pipewire.conf.d/",
        f"  cp -a /mnt/sentry-backup/critical-configs/pipewire/99-lowlatency.conf {arch_mount}/etc/pipewire/pipewire.conf.d/ 2>/dev/null || true",
        "",
        "# 10. Add NixOS ghost entry to GRUB",
        f"  # NixOS entry already in GRUB — user selects at boot",
        f"  echo 'To rollback: boot NixOS @ subvolume via GRUB menu'",
        "",
        "# 11. Done — reboot and select Arch",
        "echo 'REBOOT NOW → select Arch from GRUB menu'",
        "echo 'Instant rollback: select NixOS from GRUB menu'",
    ]

    return "\n".join(lines) + "\n"


def build_kexec_script(host: str, plan: dict) -> str:
    """Generate kexec headless install script using serial console."""
    lines = [
        "#!/usr/bin/env bash",
        f"# kexec headless install for {host} (serial console)",
        "# Generated by install.py — HARD REBOOT, REVIEW FIRST",
        "set -euo pipefail",
        "",
        "# 1. Extract kernel + initrd from omarchy ISO",
        "ISO_PATH=${OMARCHY_ISO:-/home/j_kro/omarchy-test/omarchy-4.0.0.iso}",
        "mkdir -p /tmp/kexec-extract",
        "xorriso -osirrox on -indev $ISO_PATH -extract /arch/boot/x86_64/ /tmp/kexec-extract/ 2>/dev/null",
        "KERNEL=/tmp/kexec-extract/vmlinuz-linux-t2",
        "INITRD=/tmp/kexec-extract/initramfs-linux-t2.img",
        "",
        "# 2. Serve ISO over HTTP (from another terminal on local network)",
        "echo 'In another terminal: cd /home/j_kro/omarchy-test && python3 -m http.server 8091'",
        "echo 'Waiting for HTTP server... press Ctrl-C and start it manually if needed'",
        "",
        "# 3. Load kernel via kexec",
        "# Serial console + DHCP-less networking + ISO fetch from HTTP",
        'kmsg="console=ttyS0,115200 earlyprintk=vga ip=10.1.1.199::10.1.1.1:255.255.255.0::eth0:on"',
        'kmsg="$kmsg boot=live live.url=http://10.1.1.130:8091/omarchy-4.0.0.iso live.fetch=/omarchy-4.0.0.iso"',
        f'kexec -l $KERNEL --initrd=$INITRD --append "$kmsg" --reuse-cmdline',
        "",
        "# 4. Boot (HARD REBOOT — no rollback except power cycle)",
        'kexec -e',
    ]
    return "\n".join(lines) + "\n"


