def method_vm(args: argparse.Namespace) -> int:
    """Boot the omarchy ISO in QEMU with backup data attached as 9p share."""
    iso = Path(args.iso)
    if not iso.exists():
        print(f"error: ISO not found at {iso}", file=sys.stderr)
        return 2

    qemu_cmd = [
        "qemu-system-x86_64",
        "-machine", "q35,accel=kvm",
        "-cpu", "host",
        "-smp", str(args.smp or os.cpu_count() or 4),
        "-m", str(args.mem or 4096),
        "-netdev", "user,id=net0,net=192.168.15.0/24",
        "-device", "virtio-net,netdev=net0",
        "-display", args.display or "none",
        "-serial", "stdio",
        "-boot", "d",
        "-cdrom", str(iso),
    ]

    if args.attach:
        qemu_cmd += [
            "-virtfs", f"local,path={args.attach},security_model=passthrough,mount_tag=backup",
        ]

    if args.dry_run:
        print("DRY RUN — QEMU command:")
        print("  " + " \\\n  ".join(qemu_cmd))
        if args.attach:
            print("\n  Mount in live session: mount -t 9p backup /mnt")
        return 0

    print(f"Booting omarchy ISO in QEMU")
    print(f"  ISO: {iso}")
    if args.attach:
        print(f"  Backup 9p share: mount -t 9p backup /mnt")
    print(f"  Serial: stdio (ISO TUI visible here)")
    print(f"  Display: {args.display or 'none'}")

    try:
        proc = subprocess.run(qemu_cmd, timeout=args.timeout or 300)
        return proc.returncode
    except KeyboardInterrupt:
        print("\nQEMU stopped by user")
        return 0
    except subprocess.TimeoutExpired:
        print(f"QEMU timed out after {args.timeout}s")
        return 0


def method_kexec(args: argparse.Namespace) -> int:
    """Generate kexec boot script for headless install."""
    iso = Path(args.iso) if args.iso else Path("/home/j_kro/omarchy-test/omarchy-4.0.0.iso")
    if not iso.exists():
        print(f"error: ISO not found at {iso}", file=sys.stderr)
        return 2

    iso_extract = Path("/tmp/omarchy-kexec")
    iso_extract.mkdir(exist_ok=True)

    subprocess.run([
        "xorriso", "-osirrox", "on", "-indev", str(iso),
        "-extract", "/arch/boot/x86_64/", str(iso_extract)
    ], check=False, capture_output=True)

    kernel = iso_extract / "vmlinuz-linux-t2"
    initrd = iso_extract / "initramfs-linux-t2.img"

    if not kernel.exists() or not initrd.exists():
        print(f"error: kernel/initrd not found in {iso_extract}", file=sys.stderr)
        return 2

    kmsg = args.kmsg or "console=ttyS0,115200 earlyprintk=vga"
    ip = args.ip or "10.1.1.199::10.1.1.1:255.255.255.0::eth0:on"
    iso_url = f"http://10.1.1.130:8091/{iso.name}"

    cmd_str = (
        f"kexec -l {kernel} --initrd={initrd} "
        f"--append '{kmsg} ip={ip} boot=live live.url={iso_url} live.fetch=/{iso.name}' "
        f"--reuse-cmdline"
    )

    print("\nkexec boot script:")
    print(f"  {cmd_str}")
    print(f"\nWARNING: HARD REBOOT — current NixOS session will be replaced")
    print(f"Start HTTP server first: cd {iso.parent} && python3 -m http.server 8091")

    if args.dry_run:
        return 0

    if not args.yes:
        resp = input("\nProceed with kexec boot? (yes/NO): ")
        if resp != "yes":
            print("Aborted.")
            return 0

    subprocess.run([
        "kexec", "-l", str(kernel), "--initrd", str(initrd),
        "--append", f"{kmsg} ip={ip} boot=live live.url={iso_url} live.fetch=/{iso.name}",
        "--reuse-cmdline"
    ], check=True)
    print("kexec loaded. Execute `kexec -e` to boot now.")
    return 0


