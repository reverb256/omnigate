"""omnigate install — Git-based NixOS→Arch transformation executor.

Methods:
  ghost       Subvolume-based transform (NO resize — uses btrfs subvolumes)
  kexec       Headless boot ISO via kexec (serial console)
  vm          Test in QEMU with backup 9p share
  full-wipe   Backup → wipe → install (slowest, most reliable)

Usage:
  python3 install.py --method ghost --host zephyr --dry-run
  python3 install.py --method kexec --host zephyr --iso <path>
  python3 install.py --method vm --iso <path> --attach <backup>
"""
